#!/usr/bin/env node
// Living plan for people and agents. docs/tasks.json is the source of truth;
// docs/PLAN.md (map + to-do list) is generated from it by this script.
//
//   node scripts/plan.mjs                 regenerate docs/PLAN.md
//   node scripts/plan.mjs ready           list tasks that can start now (JSON)
//                                         tasks with placeholder: true are never ready; they need a spec first
//   node scripts/plan.mjs show <ID>       one task with its deps and dependents (JSON)
//   node scripts/plan.mjs claim <ID> <agent>
//   node scripts/plan.mjs review <ID>     work is on a branch / PR, waiting for review
//   node scripts/plan.mjs done <ID>
//   node scripts/plan.mjs release <ID>    give a claimed or in-review task back
//   node scripts/plan.mjs check           validate the graph and that PLAN.md is current (CI)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const TASKS = join(root, 'docs/tasks.json');
const PLAN = join(root, 'docs/PLAN.md');
const STATUSES = ['todo', 'doing', 'review', 'done'];
// Independent QA criteria must exist before a task is claimed (docs/qa/README.md).
const qaFile = id => join(root, 'docs/qa', id + '.md');
const hasQa = id => existsSync(qaFile(id));
const SIZE = { 1: '≤1 wk', 2: '1–2 wks', 3: '2–3 wks' };

const data = JSON.parse(readFileSync(TASKS, 'utf8'));
const byId = Object.fromEntries(data.tasks.map(t => [t.id, t]));
const phaseName = id => (data.phases.find(p => p.id === id[0]) || {}).name || '';
const dependents = {};
data.tasks.forEach(t => t.deps.forEach(d => (dependents[d] ||= []).push(t.id)));

function fail(msg) { console.error('plan: ' + msg); process.exit(1); }

function validate() {
  const errs = [];
  data.tasks.forEach(t => {
    if (!STATUSES.includes(t.status)) errs.push(`${t.id}: unknown status "${t.status}"`);
    t.deps.forEach(d => { if (!byId[d]) errs.push(`${t.id}: unknown dependency ${d}`); });
    if (t.status !== 'todo' && t.status !== 'done' && !t.owner) errs.push(`${t.id}: ${t.status} without an owner`);
    if (t.status !== 'todo' && !hasQa(t.id)) errs.push(`${t.id}: ${t.status} without QA criteria (docs/qa/${t.id}.md)`);
  });
  const seen = {}, stack = {};
  const loop = id => { if (stack[id]) return true; if (seen[id]) return false; seen[id] = stack[id] = true; const r = byId[id].deps.filter(d => byId[d]).some(loop); stack[id] = false; return r; };
  if (data.tasks.some(t => loop(t.id))) errs.push('dependencies form a loop');
  return errs;
}

const waitingOn = t => t.deps.filter(d => byId[d].status !== 'done');
const isReady = t => t.status === 'todo' && !t.placeholder && !waitingOn(t).length;

// Critical path: longest chain by size ending at the last launch task.
function criticalPath() {
  const ef = {};
  const finish = id => ef[id] ?? (ef[id] = byId[id].size + Math.max(0, ...byId[id].deps.map(finish)));
  data.tasks.forEach(t => finish(t.id));
  const end = data.tasks.filter(t => t.id[0] === 'L').map(t => t.id).sort((a, b) => ef[b] - ef[a])[0];
  const path = [];
  for (let id = end; id; ) { path.unshift(id); const ds = byId[id].deps; id = ds.length ? ds.reduce((a, b) => (ef[a] >= ef[b] ? a : b)) : null; }
  return { path, weeks: ef[end] };
}

function render() {
  const crit = criticalPath(), critSet = new Set(crit.path);
  const group = s => data.tasks.filter(t => t.status === s);
  const ready = data.tasks.filter(isReady);
  const needsSpec = data.tasks.filter(t => t.status === 'todo' && t.placeholder);
  const blocked = data.tasks.filter(t => t.status === 'todo' && !t.placeholder && !isReady(t));
  const row = t => `| ${t.id} | ${t.title} | ${phaseName(t.id)} | ${SIZE[t.size]}${critSet.has(t.id) ? ' · critical' : ''} | ${hasQa(t.id) ? '[criteria](qa/' + t.id + '.md)' : '**needs criteria**'} |`;
  const lines = [];
  lines.push('# Plan', '', '<!-- Generated by `node scripts/plan.mjs` from docs/tasks.json. Do not edit by hand. -->', '');
  lines.push(`**${group('done').length} of ${data.tasks.length} done** · ${ready.length} ready · ${group('doing').length} in progress · ${group('review').length} in review · ${blocked.length} blocked · ${needsSpec.length} need a spec`, '');
  lines.push(`Critical path: ${crit.path.join(' → ')} (up to ${crit.weeks} weeks)`, '');
  lines.push('## Ready to start', '', 'Pick from here. Claim with `node scripts/plan.mjs claim <ID> <agent>`. A task can be claimed only once its QA criteria exist.', '');
  if (ready.length) { lines.push('| ID | Task | Phase | Size | QA |', '|---|---|---|---|---|'); ready.forEach(t => lines.push(row(t))); lines.push(''); ready.forEach(t => lines.push(`- **${t.id} done when:** ${t.done_when}`)); }
  else lines.push('_Nothing is ready. Everything left is claimed or waiting._');
  lines.push('', '## In progress', '');
  const active = [...group('doing'), ...group('review')];
  if (active.length) { lines.push('| ID | Task | Status | Owner | Since |', '|---|---|---|---|---|'); active.forEach(t => lines.push(`| ${t.id} | ${t.title} | ${t.status === 'doing' ? 'In progress' : 'Review'} | ${t.owner} | ${t.updated || ''} |`)); }
  else lines.push('_Nothing claimed yet._');
  lines.push('', '## Blocked', '');
  if (blocked.length) { lines.push('| ID | Task | Waiting on |', '|---|---|---|'); blocked.forEach(t => lines.push(`| ${t.id} | ${t.title} | ${waitingOn(t).join(', ')} |`)); }
  else lines.push('_Nothing blocked._');
  lines.push('', '## Needs a spec (placeholder)', '', 'Not claimable yet. A person writes the spec, then sets `placeholder` to false in docs/tasks.json.', '');
  if (needsSpec.length) { lines.push('| ID | Task | Waiting on |', '|---|---|---|'); needsSpec.forEach(t => lines.push(`| ${t.id} | ${t.title} | ${waitingOn(t).join(', ') || '—'} |`)); }
  else lines.push('_No placeholders._');
  lines.push('', '## Done', '');
  lines.push(group('done').length ? group('done').map(t => `- ${t.id} ${t.title}${t.owner ? ' (' + t.owner + ')' : ''}`).join('\n') : '_Nothing done yet._');

  lines.push('', '## Dependency map', '', mapIntro(crit), '', '```mermaid', ...mapLines(crit, critSet), '```', '', MAP_KEY, '');
  return lines.join('\n');
}

// ---- Dependency map (drawing only; tasks.json is unchanged) ----
// Lanes group open work by what it delivers, in priority order. Done tasks collapse into one node,
// implied edges are dropped (transitive reduction over open tasks), and each task shows its slack:
// how many weeks it can slip before the pilot does. Zero slack is the critical path.
const LANES = [
  ['trust', 'Trust: privacy, feedback, fairness', ['A1', 'A2', 'A5', 'A7', 'A8', 'A9', 'A10', 'M6', 'M7']],
  ['tracker', 'Tracker and insight', ['M1', 'M2', 'M3', 'M4', 'M5']],
  ['curriculum', 'Curriculum and publishing', ['F6', 'C5', 'C6', 'C7']],
  ['teacher', 'Teacher console', ['T1', 'T2', 'T3', 'T4', 'T5', 'T6', 'T7', 'T8', 'A3', 'A4', 'A6']],
  ['student', 'Student app', ['S5', 'S1', 'S2', 'S3', 'S4']],
  ['launch', 'Pilot', ['L1']],
  ['later', 'After the pilot', ['X1', 'X2']],
];
const PILOT = 'L1';
const MAP_KEY = 'Key: red border = critical path (no slack); green = ready; purple = in progress; amber = in review; grey = waiting. The number under each task is its slack: weeks it can slip before the pilot does. Done work is collapsed into one box, and arrows already implied by another path are left out of the drawing (tasks.json keeps every dependency).';

function slack() {
  const ef = {}, ls = {};
  const finish = id => ef[id] ?? (ef[id] = byId[id].size + Math.max(0, ...byId[id].deps.map(finish)));
  data.tasks.forEach(t => finish(t.id));
  // Slack is measured against the pilot; work that only follows the pilot has none to report.
  const end = ef[PILOT];
  const feeds = new Set(), up = id => { if (feeds.has(id)) return; feeds.add(id); byId[id].deps.forEach(up); };
  up(PILOT);
  const lf = {};
  const latest = id => lf[id] ?? (lf[id] = Math.min(end, ...(dependents[id] || []).filter(c => feeds.has(c)).map(c => latest(c) - byId[c].size)));
  return Object.fromEntries(data.tasks.map(t => [t.id, feeds.has(t.id) ? latest(t.id) - ef[t.id] : null]));
}

function openEdges() {
  const open = new Set(data.tasks.filter(t => t.status !== 'done' && !t.placeholder).map(t => t.id));
  const edges = [];
  data.tasks.forEach(t => { if (open.has(t.id)) t.deps.forEach(d => { if (open.has(d)) edges.push([d, t.id]); }); });
  const out = {};
  edges.forEach(([a, b]) => (out[a] ||= []).push(b));
  const reach = (from, to, skip) => {
    const seen = new Set(), st = [from];
    while (st.length) { const x = st.pop(); for (const y of out[x] || []) { if (x === from && y === skip) continue; if (y === to) return true; if (!seen.has(y)) { seen.add(y); st.push(y); } } }
    return false;
  };
  return { open, edges: edges.filter(([a, b]) => !reach(a, b, b)) };
}

function mapIntro(crit) {
  return `Open work only, grouped by what it delivers and ordered by priority. Critical path: ${crit.path.filter(id => byId[id].status !== 'done').join(' → ')} (about ${crit.weeks} weeks end to end). A rendered snapshot is in \`docs/plan-map.png\`.`;
}

function mapLines(crit, critSet) {
  const sl = slack(), { open, edges } = openEdges();
  const done = data.tasks.filter(t => t.status === 'done');
  const cls = t => (t.status === 'todo' ? (t.placeholder ? 'spec' : isReady(t) ? 'ready' : 'todo') : t.status);
  const label = t => `${t.id} · ${t.title.replace(/"/g, "'")}<br/><small>${sl[t.id] === null ? 'after the pilot' : sl[t.id] === 0 ? 'critical' : '+' + sl[t.id] + ' wk slack'}</small>`;
  const L = ['flowchart LR', `  DONE(["Done: ${done.length} tasks<br/><small>${done.map(t => t.id).join(' ')}</small>"])`];
  const placed = new Set();
  LANES.forEach(([key, name, ids]) => {
    const here = ids.filter(id => open.has(id));
    if (!here.length) return;
    L.push(`  subgraph ${key}["${name}"]`, '    direction LR');
    here.forEach(id => { placed.add(id); L.push(`    ${id}["${label(byId[id])}"]`); });
    L.push('  end');
  });
  const rest = [...open].filter(id => !placed.has(id));
  if (rest.length) { L.push('  subgraph other["Other"]'); rest.forEach(id => L.push(`    ${id}["${label(byId[id])}"]`)); L.push('  end'); }
  const roots = [...open].filter(id => !byId[id].deps.some(d => open.has(d)) && byId[id].status !== 'done');
  roots.forEach(id => L.push(`  DONE -.-> ${id}`));
  // Non-critical edges into the pilot collapse into one arrow per lane.
  const laneOf = id => (LANES.find(([, , ids]) => ids.includes(id)) || ['other'])[0];
  const laneToPilot = new Set();
  edges.forEach(([a, b]) => {
    if (b === PILOT && sl[a] !== 0 && laneOf(a) !== laneOf(PILOT)) { laneToPilot.add(laneOf(a)); return; }
    L.push(`  ${a} ${sl[a] === 0 && sl[b] === 0 ? '==>' : '-->'} ${b}`);
  });
  laneToPilot.forEach(k => L.push(`  ${k} --> ${PILOT}`));
  // Arrows: light grey by default, critical-path arrows red and thick.
  const arrows = L.filter(x => / (-->|==>|-\.->) /.test(x));
  L.push('  linkStyle default stroke:#8b8fa3,stroke-width:1.3px');
  const critIdx = arrows.map((x, i) => (x.includes('==>') ? i : -1)).filter(i => i >= 0);
  if (critIdx.length) L.push(`  linkStyle ${critIdx.join(',')} stroke:#e5484d,stroke-width:3px`);
  LANES.forEach(([key]) => L.push(`  style ${key} fill:#161826,stroke:#3a3d52,color:#b2b6ca`));
  L.push('  classDef todo fill:#232532,stroke:#75798c,color:#e9e9ed');
  L.push('  classDef ready fill:#1d3329,stroke:#6fcf97,color:#e9e9ed');
  L.push('  classDef doing fill:#2b2741,stroke:#9184d9,color:#e9e9ed,stroke-width:2px');
  L.push('  classDef review fill:#3a2f1b,stroke:#e6b45c,color:#e9e9ed,stroke-width:2px');
  L.push('  classDef spec fill:#161826,stroke:#968ae0,color:#b2b6ca,stroke-dasharray:6 4');
  L.push('  classDef done fill:#1d3329,stroke:#6fcf97,color:#9397ab,stroke-dasharray:3 3');
  L.push('  classDef crit stroke:#e5484d,stroke-width:3px');
  ['todo', 'ready', 'doing', 'review', 'spec'].forEach(c => { const ids = [...open].filter(id => cls(byId[id]) === c); if (ids.length) L.push(`  class ${ids.join(',')} ${c}`); });
  L.push('  class DONE done');
  const crits = [...open].filter(id => sl[id] === 0);
  if (crits.length) L.push(`  class ${crits.join(',')} crit`);
  return L;
}

function save() {
  writeFileSync(TASKS, JSON.stringify(data, null, 2) + '\n');
  writeFileSync(PLAN, render());
}

function setStatus(id, status, owner) {
  const t = byId[id];
  if (!t) fail(`no task ${id}`);
  t.status = status;
  if (owner !== undefined) t.owner = owner;
  t.updated = new Date().toISOString().slice(0, 10);
  save();
  console.log(`${id} → ${status}${t.owner ? ' (' + t.owner + ')' : ''}`);
}

const [cmd, id, agent] = process.argv.slice(2);
const errs = validate();
if (errs.length && cmd !== 'check') fail(errs.join('\n'));

switch (cmd) {
  case undefined:
  case 'render': save(); console.log('docs/PLAN.md updated'); break;
  case 'ready': console.log(JSON.stringify(data.tasks.filter(isReady).map(({ id, title, size, done_when }) => ({ id, title, size, done_when })), null, 2)); break;
  case 'show': {
    const t = byId[id] || fail(`no task ${id}`);
    console.log(JSON.stringify({ ...t, phase: phaseName(t.id), waiting_on: waitingOn(t), unblocks: dependents[t.id] || [] }, null, 2));
    break;
  }
  case 'claim': {
    const t = byId[id] || fail(`no task ${id}`);
    if (!agent) fail('claim needs an agent name: claim <ID> <agent>');
    if (t.status !== 'todo') fail(`${id} is already ${t.status}${t.owner ? ' by ' + t.owner : ''}`);
    if (t.placeholder) fail(`${id} is a placeholder with no spec yet. Pick another task, or ask a person to write the spec`);
    if (!hasQa(id)) fail(`${id} has no QA criteria yet (docs/qa/${id}.md). The coordinator writes them before the task can be claimed`);
    if (!isReady(t)) fail(`${id} is waiting on ${waitingOn(t).join(', ')}`);
    setStatus(id, 'doing', agent);
    break;
  }
  case 'review': { const t = byId[id] || fail(`no task ${id}`); if (t.status !== 'doing') fail(`${id} is ${t.status}, not in progress`); setStatus(id, 'review'); break; }
  case 'done': { const t = byId[id] || fail(`no task ${id}`); if (t.status === 'todo') fail(`${id} was never claimed`); setStatus(id, 'done'); break; }
  case 'release': { const t = byId[id] || fail(`no task ${id}`); if (t.status !== 'doing' && t.status !== 'review') fail(`${id} is ${t.status}, not claimed`); setStatus(id, 'todo', null); break; }
  case 'check': {
    if (errs.length) fail(errs.join('\n'));
    let current = '';
    try { current = readFileSync(PLAN, 'utf8'); } catch {}
    if (current !== render()) fail('docs/PLAN.md is out of date. Run: node scripts/plan.mjs');
    console.log('plan: ok');
    break;
  }
  default: fail(`unknown command "${cmd}"`);
}
