// Assemble kernel.wat into packages/ai/src/ner-kernel.ts (needs `wabt`; the app does not).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import wabt from 'wabt';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const w = await wabt();
const mod = w.parseWat('kernel.wat', readFileSync(here('kernel.wat'), 'utf8'), { simd: true });
const { buffer } = mod.toBinary({});
const base64 = Buffer.from(buffer).toString('base64');
writeFileSync(
  here('../../packages/ai/src/ner-kernel.ts'),
  `// Generated by scripts/model/build_kernel.mjs from kernel.wat. Do not edit.\nexport const KERNEL_WASM_BASE64 =\n  '${base64}';\n`,
);
console.log(buffer.length, 'bytes');
